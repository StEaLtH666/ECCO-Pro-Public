class Pub0Error(AssertionError):
    """A pub0 site, count or hash does not match its declaration (a failed proof, never a skipped one)."""


def sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def line_sha(line: str) -> str:
    return sha(line)[:16]


def read_repo(rel: str, root: Path | None = None) -> str:
    """A repo text file as the suites read it (Path.read_text: universal newlines -> LF)."""
    return ((root or REPO) / rel).read_text(encoding="utf-8")


# ---------------------------------------------------------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------------------------------------------------------
def fingerprint(files: list) -> str:
    """Deterministic sha256 of the canonical JSON of the manifest's file records (pinned in _scope_chain.PUB0_FINGERPRINT)."""
    return sha(json.dumps(files, sort_keys=True, separators=(",", ":"), ensure_ascii=True))


@lru_cache(maxsize=None)
def _manifest_cached(path: str) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def manifest() -> dict:
    return _manifest_cached(str(REPO / MANIFEST_REL))


def records(m: dict | None = None) -> dict:
    return {f["path"]: f for f in (m or manifest())["files"]}


def is_target(rel: str, m: dict | None = None) -> bool:
    return rel in records(m)


def _sites_by_line(rec: dict) -> list:
    return [(int(n), h, [(int(c), k) for c, k in sites]) for n, h, sites in rec["lines"]]


# ---------------------------------------------------------------------------------------------------------------------------
# The two directions
# ---------------------------------------------------------------------------------------------------------------------------
def _private_len(kind: str) -> int:
    return OCTOPUS_LEN[kind] if kind in OCTOPUS_LEN else len(PRIVATE_TOKEN[kind])


def _octopus_masked(rel: str, private_text: str, rec: dict) -> tuple[str, dict]:
    """The private text with every declared Octopus site replaced by its placeholder (the slug untouched) and the values found."""
    lines = private_text.split("\n")
    values: dict[str, set] = {}
    for n, _h, sites in _sites_by_line(rec):
        if n > len(lines):
            raise Pub0Error(f"pub0 {rel}: declared line {n} is past the end of the file ({len(lines)} lines)")
        line, out, pos, delta = lines[n - 1], [], 0, 0
        for col, kind in sites:
            pcol = col - delta
            plen = _private_len(kind)
            tok = line[pcol:pcol + plen]
            if kind in OCTOPUS_SHAPE:
                if not OCTOPUS_SHAPE[kind].fullmatch(tok):
                    raise Pub0Error(f"pub0 {rel}:{n}: no {kind}-shaped value at column {pcol}")
                values.setdefault(kind, set()).add(tok)
                out.append(line[pos:pcol] + OCTOPUS_PLACEHOLDER[kind])
                pos = pcol + plen
            delta += len(PUBLIC_TOKEN[kind]) - plen
        if any(k in OCTOPUS_SHAPE for _c, k in sites):
            lines[n - 1] = "".join(out) + line[pos:]
    return "\n".join(lines), values


def forward(rel: str, private_text: str, m: dict | None = None) -> str:
    """Private (source) text -> the public text. Accepts ONLY the declared source; raises Pub0Error otherwise."""
    recs = records(m)
    if rel not in recs:
        raise Pub0Error(f"pub0: {rel} is not a pub0 target")
    rec = recs[rel]
    masked, values = _octopus_masked(rel, private_text, rec)
    for kind, vals in values.items():
        if len(vals) != 1:
            raise Pub0Error(f"pub0 {rel}: {len(vals)} different {kind} values (exactly one is declared)")
    if "import_mpan" in values and values["import_mpan"] == values.get("export_mpan"):
        raise Pub0Error(f"pub0 {rel}: the import and export MPAN are the same value")
    if sha(masked) != rec["source_sha256"]:
        raise Pub0Error(f"pub0 {rel}: the source is not the declared pub0 source (sha256 {sha(masked)[:16]} != "
                        f"{rec['source_sha256'][:16]}); regenerate the manifest only for a deliberate new export base")
    lines = masked.split("\n")
    n_prefix_sites = n_octo_sites = n_wording_sites = n_attribution_sites = 0
    for n, h, sites in _sites_by_line(rec):
        line, out, pos, delta = lines[n - 1], [], 0, 0
        for col, kind in sites:
            pcol = col - delta
            if kind in OCTOPUS_SHAPE:            # already the placeholder (masked above)
                plen = len(OCTOPUS_PLACEHOLDER[kind])
                n_octo_sites += kind == "meter_serial"
            else:
                plen = len(PRIVATE_TOKEN[kind])
                if line[pcol:pcol + plen] != PRIVATE_TOKEN[kind]:
                    raise Pub0Error(f"pub0 {rel}:{n}: expected {kind} token at column {pcol}")
                n_prefix_sites += kind in ("slug", "keep", "keep_prefix")
                n_wording_sites += kind == "wording"
                n_attribution_sites += kind == "attribution"
            out.append(line[pos:pcol] + PUBLIC_TOKEN[kind])
            pos = pcol + plen
            delta += len(PUBLIC_TOKEN[kind]) - plen
        new = "".join(out) + line[pos:]
        if line_sha(new) != h:
            raise Pub0Error(f"pub0 {rel}:{n}: the public line does not hash to the recorded {h}")
        lines[n - 1] = new
    public = "\n".join(lines)
    # Coverage: every occurrence is a declared site - no more, no fewer.
    if private_text.count(PRIVATE_AREA_PREFIX) != n_prefix_sites:
        raise Pub0Error(f"pub0 {rel}: {private_text.count(PRIVATE_AREA_PREFIX)} private-prefix occurrences, {n_prefix_sites} declared")
    if rel != SELF_REL and private_text.count(WORDING_PRIVATE) != n_wording_sites:
        raise Pub0Error(f"pub0 {rel}: {private_text.count(WORDING_PRIVATE)} provenance-wording occurrences, {n_wording_sites} declared")
    if rel != SELF_REL and private_text.count(ATTRIBUTION_PRIVATE) != n_attribution_sites:
        raise Pub0Error(f"pub0 {rel}: {private_text.count(ATTRIBUTION_PRIVATE)} personal-attribution occurrences, "
                        f"{n_attribution_sites} declared")
    if len(OCTOPUS_ID.findall(private_text)) != n_octo_sites:
        raise Pub0Error(f"pub0 {rel}: {len(OCTOPUS_ID.findall(private_text))} Octopus ids, {n_octo_sites} declared")
    for kind, vals in values.items():
        for v in vals:
            if v in public:
                raise Pub0Error(f"pub0 {rel}: a {kind} value survives outside the declared sites")
    if sha(public) != rec["result_sha256"]:
        raise Pub0Error(f"pub0 {rel}: the public text does not hash to the recorded result {rec['result_sha256'][:16]}")
    return public


def reverse(rel: str, public_text: str, m: dict | None = None) -> str:
    """Public text -> the exact private representation (proof direction; edit-local, like every chain reverter). Octopus sites keep
    their placeholders (irreversible by design)."""
    recs = records(m)
    if rel not in recs:
        raise Pub0Error(f"pub0: {rel} is not a pub0 target")
    lines = public_text.split("\n")
    for n, h, sites in _sites_by_line(recs[rel]):
        if n > len(lines) or line_sha(lines[n - 1]) != h:
            raise Pub0Error(f"pub0 {rel}:{n}: not the recorded pub0 public line (its edit is absent or altered)")
        line, out, pos = lines[n - 1], [], 0
        for col, kind in sites:
            tok = PUBLIC_TOKEN[kind]
            if line[col:col + len(tok)] != tok:
                raise Pub0Error(f"pub0 {rel}:{n}: expected the public {kind} token at column {col}")
            out.append(line[pos:col] + (PRIVATE_TOKEN[kind] if kind in REVERSIBLE else tok))
            pos = col + len(tok)
        lines[n - 1] = "".join(out) + line[pos:]
    return "\n".join(lines)


def reverter(rel: str):
    """The chain reverter of a pub0-edited chain-pinned artifact (_scope_chain.PUB0)."""
    def revert(text: str) -> str:
        return reverse(rel, text)
    revert.__name__ = f"pre_pub0_{Path(rel).stem}"
    return revert


def private_view(rel: str, text: str) -> str:
    """What an older suite hashes / reverts: `text` exactly as the private tree spells it. The identity in the private tree and for
    every file pub0 does not touch; reverse() in the public export (a declared site that is absent or altered raises). A target that
    is not a declared PROOF_VIEW raises in both trees."""
    if not is_target(rel):
        return text
    if rel not in PROOF_VIEWS:
        raise Pub0Error(f"pub0: {rel} is not a declared PROOF_VIEW (declare it in _pub0_scope.PROOF_VIEWS and the PUB0 ledger)")
    return reverse(rel, text) if EXPORTED else text


def private_view_edited(rel: str, text: str, line_edits: dict) -> str:
    """private_view(rel, text) with a suite's own exact LINE edit applied at the same line numbers: every line of `text` equal to a key
    of `line_edits` becomes the mapped value (None removes it). pub0 maps a file line for line, so this is the private text of the
    suite's derived (reverted) text - for an older suite that pins a template it derives by replacing whole lines."""
    out = []
    for t, p in zip(text.split("\n"), private_view(rel, text).split("\n")):
        if t in line_edits:
            if line_edits[t] is not None:
                out.append(line_edits[t])
        else:
            out.append(p)
    return "\n".join(out)


def private_view_bytes(rel: str, data: bytes) -> bytes:
    """private_view() for a suite that hashes LF-normalised bytes (the frontend-folder pins)."""
    if not is_target(rel):
        return data
    return private_view(rel, data.decode("utf-8")).encode("utf-8")


# ---------------------------------------------------------------------------------------------------------------------------
# Generation (private tree only): the manifest is DERIVED from the private source, deterministic, round-trip verified
# ---------------------------------------------------------------------------------------------------------------------------
def _find_sites(rel: str, text: str) -> list:
    """[(line, private column, kind)] of every pub0 site in the private text, by the policy of the file."""
    out = []
    lines = text.split("\n")
    for i, line in enumerate(lines, 1):
        found = []
        if rel in OCTOPUS_FILES:
            for mo in OCTOPUS_ID.finditer(line):
                found.append((mo.start(1), "meter_serial"))
                found.append((mo.start(2), "export_mpan" if mo.group(3) else "import_mpan"))
        start = 0
        while True:
            j = line.find(PRIVATE_AREA_PREFIX, start)
            if j < 0:
                break
            if line.startswith(PRIVATE_SLUG, j):
                found.append((j, "keep" if rel in KEEP_FILES else "slug"))
            elif rel == SELF_REL and line.startswith(f'PRIVATE_AREA_PREFIX = "{PRIVATE_AREA_PREFIX}"', j - len('PRIVATE_AREA_PREFIX = "')):
                found.append((j, "keep_prefix"))
            else:
                raise Pub0Error(f"pub0 generate {rel}:{i}: a bare private prefix that is neither the slug nor the declared literal")
            start = j + len(PRIVATE_AREA_PREFIX)
        if rel in WORDING_FILES:
            start = 0
            while (j := line.find(WORDING_PRIVATE, start)) >= 0:
                found.append((j, "wording"))
                start = j + len(WORDING_PRIVATE)
        if rel in ATTRIBUTION_FILES:
            start = 0
            while (j := line.find(ATTRIBUTION_PRIVATE, start)) >= 0:
                found.append((j, "attribution"))
                start = j + len(ATTRIBUTION_PRIVATE)
        if rel == SELF_REL and EXPORT_FLAG_LINE.fullmatch(line):
            if line != "EXPORTED = False":
                raise Pub0Error("pub0 generate: the private tree must carry EXPORTED = False")
            found.append((len("EXPORTED = "), "export_flag"))
        out.extend((i, c, k) for c, k in sorted(found))
    return out


def generate(root: Path | None = None) -> dict:
    """The manifest for the private tree at `root` (default: this repo). Raises if the tree is already an export."""
    files = []
    for rel in TARGETS:
        text = read_repo(rel, root)
        sites = _find_sites(rel, text)
        if not sites:
            raise Pub0Error(f"pub0 generate: target {rel} carries no pub0 token")
        lines = text.split("\n")
        by_line: dict[int, list] = {}
        for n, c, k in sites:
            by_line.setdefault(n, []).append((c, k))
        recs_lines = []
        for n in sorted(by_line):
            line, out, pos, pub_sites, delta = lines[n - 1], [], 0, [], 0
            for c, k in by_line[n]:
                plen = _private_len(k)
                out.append(line[pos:c] + PUBLIC_TOKEN[k])
                pub_sites.append([c + delta, k])
                delta += len(PUBLIC_TOKEN[k]) - plen
                pos = c + plen
            new = "".join(out) + line[pos:]
            recs_lines.append([n, line_sha(new), pub_sites])
            lines[n - 1] = new
        public = "\n".join(lines)
        rec = {"path": rel, "result_sha256": sha(public), "lines": recs_lines}
        rec["source_sha256"] = sha(reverse(rel, public, {"files": [rec]}))
        files.append({"path": rel, "source_sha256": rec["source_sha256"], "result_sha256": rec["result_sha256"], "lines": recs_lines})
        m1 = {"files": [files[-1]]}
        if forward(rel, text, m1) != public or (rel not in OCTOPUS_FILES and reverse(rel, public, m1) != text):
            raise Pub0Error(f"pub0 generate {rel}: round trip failed")
    return {"schema": SCHEMA, "transition": "pub0",
            "kinds": {k: {"public": PUBLIC_TOKEN[k] if k not in ("keep", "keep_prefix") else "(kept)",
                          "reversible": k in REVERSIBLE} for k in KINDS},
            "fingerprint": fingerprint(files), "files": files}


def dumps(m: dict) -> str:
    """The canonical manifest text (one file record per line, so a review diff shows exactly which file moved)."""
    head = {k: v for k, v in m.items() if k != "files"}
    body = ",\n".join("  " + json.dumps(f, sort_keys=True, separators=(",", ":")) for f in m["files"])
    return json.dumps(head, sort_keys=True, indent=1)[:-2] + ',\n "files": [\n' + body + "\n ]\n}\n"
