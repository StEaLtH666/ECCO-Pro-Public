"""pub0 - PUBLIC-EXPORT SANITISATION as ONE declared, exact, reversible proof-chain transition.

WHY. The public repository must not spell the owner's Home Assistant device slug (its area prefix names where the dongle is)
or the Octopus meter serial / MPANs (docs/public-release/PUBLIC_RELEASE_BUILD_SPEC.md C.1 items 1-3 and 9). About forty
suites pin those very files byte for byte (sha256, exact-match reverters, chain checkpoints). A find-and-replace would turn them
red, and re-hashing them is forbidden (_scope_chain.py: "No older suite is re-hashed, ever"). So the sanitisation is a declared
transition, the project's own technique: every edit is recorded, applied exactly, verified, and undone exactly for the proofs.

WHAT pub0 CHANGES (the complete list; the spec names nothing else as a token substitution):
  slug          the private device slug (PRIVATE_SLUG) -> PUBLIC_SLUG, the slug a fresh Home Assistant install generates for
                the firmware's `name: ecco-clock-dongle` (spec C.2)
  meter_serial  the Octopus meter serial inside `octopus_energy_electricity_<serial>_<mpan>_...` ids -> `your_meter_serial`
  import_mpan   the import MPAN in those ids -> `your_import_mpan`
  export_mpan   the export MPAN (the ids that continue `_export_`) -> `your_export_mpan`
  export_flag   EXPORTED below: False -> True (the declared marker that a tree IS the pub0 export)
  wording       an unsupported provenance attribution in the register map (WORDING below: the private wording -> a neutral
                public wording; register facts unchanged; PUBLIC_RELEASE_BUILD_SPEC D)
  attribution   a personal first name in six register-map descriptions (ATTRIBUTION below: "SmartDeye/<first name>-listed" ->
                "SmartDeye-listed"; the descriptions are otherwise unchanged)
and it KEEPS, as declared exemptions (sites of kind keep / keep_prefix, counted like every other site):
  keep          (no sites since the public-export assembly) the private slug inside a generated HISTORICAL hunk module. The two
                such modules (_fbb3_ha_scope.py, _fbc3_scope.py) now carry a marker and bind the slug from PRIVATE_SLUG at import
                (their bound hunks are pinned by test_pub0_transition.py [7]), so they spell no private literal at all
  keep_prefix   the one PRIVATE_AREA_PREFIX literal below, which private_view() needs to rebuild the private text
The public export therefore carries exactly TWO private literals, both reverter data in THIS module and nowhere else: the
PRIVATE_AREA_PREFIX literal and the ATTRIBUTION_PRIVATE literal (machine-checked by test_pub0_privacy.py [1] and
tools/tests/test_public_privacy.py [1]). The register map is chain-pinned at the root checkpoint, so only an EXACT reverse can
reproduce that pin; removing the first name from the reverter too would mean re-hashing the root pin, which is forbidden.

HOW. registry/tests/fixtures/pub0_manifest.json (GENERATED by generate() / tools/public/pub0.py; reviewed, never hand-edited)
lists every target file with its source and result sha256 and, per changed line, the line number, the sha256 (16 hex) of the
PUBLIC line and the sites [column in the public line, kind]. The manifest spells no private value: the private side of a site
is the rule of its kind, the Octopus values are matched by shape and never stored.
  forward(rel, private_text) -> public text   (export direction) ACCEPTS ONLY the declared source: every site's private token at
                its exact place, every private-prefix occurrence and every Octopus id in the file covered by a site (no more, no
                fewer), one value per Octopus kind, no Octopus value left anywhere, the masked source sha256 and the result
                sha256 exactly as recorded. Anything else raises Pub0Error.
  reverse(rel, public_text) -> private representation (proof direction) - edit-local like every chain reverter: each declared
                line must be exactly the recorded public line (its hash) with the public token at the recorded column, and only
                those sites are undone. It is NOT a generic replace: the slug already spelled un-prefixed in the private tree
                (`esphome.ecco_clock_dongle_fallback_profile_execute`, `sensor.ecco_clock_dongle_wifi_signal`) is left alone.
                The Octopus values are irreversible by design (not in the public tree): reverse() leaves the placeholders.
  private_view(rel, text) is what an older suite calls before a historical pin: the identity in the private tree (and for
                every file pub0 does not touch), reverse() in the public export.
The scope chain carries pub0 as an Entry (registry/tests/_scope_chain.py, PUB0) whose reverter for the only chain-pinned artifact
pub0 edits (registry/inverter_capabilities.yaml) is reverse(); it is part of CHAIN only when EXPORTED.

No I/O except reading the manifest and repo files.
"""

